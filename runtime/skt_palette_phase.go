package runtime

// SKTPalettePhases is the number of blink phases in the SKT palette. GVM2X
// keeps one 182-entry remap row per gamma level and phase (table 0x47CB6C);
// its slot-0 timer selects the phase from a counter modulo six.
const SKTPalettePhases = 6

// SKTGammaColorPhase is SKTGammaColor for one blink phase. Phase 0 is the
// row SKTGammaColor returns; the other phases differ only for the blinking
// grays (5..15) and the blinking colors (140..181). Every gamma row is the
// gamma-3 row passed through the same gamma curve.
func SKTGammaColorPhase(gamma, index, phase uint8) (packed byte, ok bool) {
	if phase >= SKTPalettePhases {
		return 0, false
	}
	if phase == 0 || gamma > 6 {
		return SKTGammaColor(gamma, index)
	}
	switch {
	case index >= 5 && index <= 15:
		packed = sktBlinkingGrays[index-5][phase-1]
	case index >= 140 && index <= 181:
		packed = sktBlinkingColors[index-140][phase-1]
	default:
		return SKTGammaColor(gamma, index)
	}
	return applySKTGamma(gamma, packed), true
}

