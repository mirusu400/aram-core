// Command genappmicro derives the untraced application executor from the
// guarded Thumb executor. Instruction semantics have a single editable source.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"strings"
)

func main() {
	source := flag.String("source", "jit_thumb_micro.go", "guarded executor source")
	output := flag.String("output", "jit_thumb_application_gen.go", "generated application executor")
	check := flag.Bool("check", false, "verify the checked-in executor without writing")
	flag.Parse()
	if err := generate(*source, *output, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(source, output string, check bool) error {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, source, nil, parser.ParseComments)
	if err != nil {
		return err
	}
	var executor *ast.FuncDecl
	for _, decl := range file.Decls {
		if fn, ok := decl.(*ast.FuncDecl); ok && fn.Name.Name == "executeThumbMicroBlock" {
			executor = fn
		}
	}
	if executor == nil || executor.Body == nil {
		return fmt.Errorf("guarded Thumb executor not found")
	}
	var loop *ast.RangeStmt
	for _, stmt := range executor.Body.List {
		if candidate, ok := stmt.(*ast.RangeStmt); ok {
			if loop != nil {
				return fmt.Errorf("guarded executor has multiple outer loops")
			}
			loop = candidate
		}
	}
	if loop == nil || len(loop.Body.List) < 4 {
		return fmt.Errorf("guarded instruction loop not found")
	}
	nodeString := func(node ast.Node) string {
		var text bytes.Buffer
		if err := format.Node(&text, fset, node); err != nil {
			panic(err)
		}
		return text.String()
	}
	compact := func(text string) string { return strings.Join(strings.Fields(text), "") }
	if nodeString(loop.Body.List[0]) != "in := &instructions[index]" ||
		nodeString(loop.Body.List[1]) != "pc := in.pc" ||
		compact(nodeString(loop.Body.List[2])) != "ifcollectThumbMicro{b.recordThumbMicro(in)}" {
		return fmt.Errorf("instruction prelude changed; review application generation")
	}
	first := -1
	rawEncoding := false
	for index, stmt := range loop.Body.List {
		switch nodeString(stmt) {
		case "instruction := in.raw":
			rawEncoding = true
		case "b.regs[cpu.RegisterPC] = pc + 2":
			first = index
		}
	}
	if first < 0 || !rawEncoding || nodeString(executor.Body.List[len(executor.Body.List)-1]) != "return blockInstructions, false, nil, nil" {
		return fmt.Errorf("architectural execution boundaries changed; review application generation")
	}
	if err := validateApplicationCachedStoreNamespace41(loop.Body.List[first:]); err != nil {
		return err
	}
	tailHelper, err := applicationCompareBranchTailHelper(fset, loop.Body.List[first:])
	if err != nil {
		return err
	}
	var body bytes.Buffer
	needsBits := false
	privateRouteGuards := 0
	privateScalarStores41 := 0
	for _, stmt := range loop.Body.List[first:] {
		var forbidden string
		ast.Inspect(stmt, func(node ast.Node) bool {
			if ident, ok := node.(*ast.Ident); ok {
				switch ident.Name {
				case "wholeSystem", "hasExecutionTraps", "traced":
					forbidden = ident.Name
				case "bits":
					needsBits = true
				}
			}
			return true
		})
		if forbidden != "" {
			return fmt.Errorf("instruction body now depends on %s; review mode separation", forbidden)
		}
		if err := specializeApplicationFlags(fset, stmt); err != nil {
			return err
		}
		if err := specializeApplicationTransfers(fset, stmt); err != nil {
			return err
		}
		guards, err := hoistApplicationPrivateRoute(stmt)
		if err != nil {
			return err
		}
		privateRouteGuards += guards
		stores41, err := cacheApplicationScalarStores41(fset, stmt)
		if err != nil {
			return err
		}
		privateScalarStores41 += stores41
		if err := rewriteApplicationBlockReturns(fset, stmt); err != nil {
			return err
		}
		body.WriteString(nodeString(stmt))
		body.WriteByte('\n')
	}
	if err := requireApplicationPrivateRouteCount(privateRouteGuards); err != nil {
		return err
	}
	if err := requireApplicationCachedScalarStores41(privateScalarStores41); err != nil {
		return err
	}
	var generated bytes.Buffer
	generated.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage interpreter\n\nimport (\n")
	if needsBits {
		generated.WriteString("\"math/bits\"\n\n")
	}
	generated.WriteString("\"github.com/mirusu400/aram-core/cpu\"\n)\n\n")
	generated.WriteString(`// executeThumbApplicationMicroBlocks runs only for private, untraced Thumb execution.
// Architectural instruction bodies come from executeThumbMicroBlock; the caller
// retains batch cancellation and the guarded partial-block path. Every full block
// entered here keeps its own generation, retirement and diagnostic boundaries.
func (b *Backend) executeThumbApplicationMicroBlocks(block *jitBlock, limit uint64) (uint64, *cpu.StopReason, error) {
var executed uint64
privateDataRoute := !b.physicalAccess && b.tlb == nil
for executed < limit {
blockInstructions := len(block.thumb)
if uint64(blockInstructions) > limit-executed {
return executed, nil, nil
}
if collectThumbMicro { b.recordThumbBlock(block) }
prefixInstructions := blockInstructions
if block.compareBranchTail != nil { prefixInstructions -= 2 }
instructions := block.thumb[:prefixInstructions]
blockGeneration := b.jitGen
blockRetired := blockInstructions
for index := range instructions {
in := &instructions[index]
pc := in.pc
if collectThumbMicro { b.recordThumbMicro(in) }
instruction := in.raw
`)
	generated.Write(body.Bytes())
	generated.WriteString(`}
if block.compareBranchTail != nil { b.executeThumbCompareBranchTail(block) }
blockDone:
executed += uint64(blockRetired)
if b.mode != cpu.ModeThumb || executed == limit {
return executed, nil, nil
}
if b.jitGen == blockGeneration && b.regs[cpu.RegisterPC] == block.start {
continue
}
pc := b.regs[cpu.RegisterPC]
var successor *jitBlock
if block.successorGen == b.jitGen {
if next := block.successors[0]; next != nil && next.start == pc {
successor = next
} else if next := block.successors[1]; next != nil && next.start == pc {
successor = next
}
}
if successor == nil {
successor = b.thumbApplicationSuccessor(block, pc)
}
if successor == nil {
return executed, nil, nil
}
block = successor
}
return executed, nil, nil
}
`)
	generated.WriteString(tailHelper)
	contents, err := format.Source(generated.Bytes())
	if err != nil {
		return err
	}
	contents, err = promoteApplicationFaultErrors41(contents)
	if err != nil {
		return err
	}
	if check {
		current, err := os.ReadFile(output)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, contents) {
			return fmt.Errorf("generated Thumb application executor is stale; run go generate ./cpu/interpreter")
		}
		return nil
	}
	return os.WriteFile(output, contents, 0o644)
}

// The application runner may continue across ordinary block boundaries, but
// faults and architectural stops still report only the completed instruction
// prefix. Reuse the guarded bodies and transform only their return convention.
func rewriteApplicationBlockReturns(fset *token.FileSet, stmt ast.Stmt) error {
	var lists []*[]ast.Stmt
	closure := false
	ast.Inspect(stmt, func(node ast.Node) bool {
		switch item := node.(type) {
		case *ast.BlockStmt:
			lists = append(lists, &item.List)
		case *ast.CaseClause:
			lists = append(lists, &item.Body)
		case *ast.FuncLit:
			closure = true
			return false
		}
		return true
	})
	if closure {
		return fmt.Errorf("instruction body contains a closure; review application exits")
	}
	for _, list := range lists {
		for index, statement := range *list {
			exit, ok := statement.(*ast.ReturnStmt)
			if !ok {
				continue
			}
			if len(exit.Results) != 4 {
				return fmt.Errorf("instruction return shape changed; review application exits")
			}
			var count bytes.Buffer
			if err := format.Node(&count, fset, exit.Results[0]); err != nil {
				return err
			}
			if value := strings.Join(strings.Fields(count.String()), ""); value != "index" && value != "index+1" {
				return fmt.Errorf("instruction retirement changed to %s; review application exits", count.String())
			}
			// The old branched result is no longer needed in private execution:
			// both branch and fallthrough PCs may have an ordinary successor.
			// Whitelist the known pure expressions; an index, receive or future
			// expression may panic or have effects even without a function call.
			var branch bytes.Buffer
			if err := format.Node(&branch, fset, exit.Results[1]); err != nil {
				return err
			}
			switch strings.Join(strings.Fields(branch.String()), "") {
			case "false", "true", "includePC", "instruction&(1<<8)!=0":
			default:
				return fmt.Errorf("instruction branch result changed to %s; review application exits", branch.String())
			}
			isNil := func(value ast.Expr) bool {
				identifier, ok := value.(*ast.Ident)
				return ok && identifier.Name == "nil"
			}
			if isNil(exit.Results[2]) && isNil(exit.Results[3]) {
				(*list)[index] = &ast.BlockStmt{List: []ast.Stmt{
					&ast.AssignStmt{Lhs: []ast.Expr{ast.NewIdent("blockRetired")}, Tok: token.ASSIGN, Rhs: []ast.Expr{exit.Results[0]}},
					&ast.BranchStmt{Tok: token.GOTO, Label: ast.NewIdent("blockDone")},
				}}
				continue
			}
			exit.Results = []ast.Expr{
				&ast.BinaryExpr{X: ast.NewIdent("executed"), Op: token.ADD, Y: &ast.CallExpr{Fun: ast.NewIdent("uint64"), Args: []ast.Expr{exit.Results[0]}}},
				exit.Results[2], exit.Results[3],
			}
		}
	}
	return nil
}

// Classify the load/store subtype at translation time without increasing the
// compact micro-op. Constants let Go remove the instruction body's secondary
// dispatch; the ordered accesses and fault/SMC exits still come from the source.
func specializeApplicationTransfers(fset *token.FileSet, stmt ast.Stmt) error {
	dispatch, ok := stmt.(*ast.SwitchStmt)
	if !ok {
		return nil
	}
	tag, ok := dispatch.Tag.(*ast.SelectorExpr)
	if !ok || tag.Sel.Name != "appOp" {
		return nil
	}
	var specialized []ast.Stmt
	for _, statement := range dispatch.Body.List {
		clause := statement.(*ast.CaseClause)
		if len(clause.List) != 1 {
			specialized = append(specialized, clause)
			continue
		}
		name, ok := clause.List[0].(*ast.Ident)
		if !ok || name.Name != "thumbImmediateTransfer" && name.Name != "thumbRegisterTransfer" {
			specialized = append(specialized, clause)
			continue
		}
		base, subtypes := "thumbAppImmediateTransferBase", 4
		if name.Name == "thumbRegisterTransfer" {
			base, subtypes = "thumbAppRegisterTransferBase", 8
		}
		for subtype := 0; subtype < subtypes; subtype++ {
			var text bytes.Buffer
			if err := format.Node(&text, fset, clause); err != nil {
				return err
			}
			parsed, err := parser.ParseFile(fset, "application-transfer.go", "package interpreter\nfunc transfer() { switch in.appOp {"+text.String()+"} }", 0)
			if err != nil {
				return err
			}
			copy := parsed.Decls[0].(*ast.FuncDecl).Body.List[0].(*ast.SwitchStmt).Body.List[0].(*ast.CaseClause)
			copy.List[0] = &ast.BinaryExpr{X: ast.NewIdent(base), Op: token.ADD, Y: &ast.BasicLit{Kind: token.INT, Value: fmt.Sprint(subtype)}}
			if subtypes == 4 {
				if err := specializeApplicationConstant(fset, copy, "byteTransfer", "instruction&(1<<12)!=0", fmt.Sprint(subtype&2 != 0)); err != nil {
					return err
				}
				if err := specializeApplicationConstant(fset, copy, "load", "instruction&(1<<11)!=0", fmt.Sprint(subtype&1 != 0)); err != nil {
					return err
				}
			} else if err := specializeApplicationConstant(fset, copy, "op", "uint32(instruction>>9)&7", fmt.Sprint(subtype)); err != nil {
				return err
			}
			specialized = append(specialized, copy)
		}
	}
	dispatch.Body.List = specialized
	return nil
}

func specializeApplicationConstant(fset *token.FileSet, clause *ast.CaseClause, name, expected, value string) error {
	for index, statement := range clause.Body {
		assignment, ok := statement.(*ast.AssignStmt)
		if !ok || assignment.Tok != token.DEFINE || len(assignment.Lhs) != 1 || len(assignment.Rhs) != 1 {
			continue
		}
		identifier, ok := assignment.Lhs[0].(*ast.Ident)
		if !ok || identifier.Name != name {
			continue
		}
		var text bytes.Buffer
		if err := format.Node(&text, fset, assignment.Rhs[0]); err != nil {
			return err
		}
		if strings.Join(strings.Fields(text.String()), "") != expected {
			return fmt.Errorf("application %s decode changed; review transfer specialization", name)
		}
		expression, err := parser.ParseExpr(value)
		if err != nil {
			return err
		}
		clause.Body[index] = &ast.DeclStmt{Decl: &ast.GenDecl{Tok: token.CONST, Specs: []ast.Spec{
			&ast.ValueSpec{Names: []*ast.Ident{ast.NewIdent(name)}, Values: []ast.Expr{expression}},
		}}}
		return nil
	}
	return fmt.Errorf("application %s decode not found; review transfer specialization", name)
}

// Encode dead flag writes as separate compact opcodes. Keeping the normal
// cases untouched avoids a liveness branch on every ordinary instruction.
func specializeApplicationFlags(fset *token.FileSet, stmt ast.Stmt) error {
	dispatch, ok := stmt.(*ast.SwitchStmt)
	if !ok {
		return nil
	}
	tag, ok := dispatch.Tag.(*ast.SelectorExpr)
	if !ok || tag.Sel.Name != "op" {
		return nil
	}
	tag.Sel.Name = "appOp"
	var deadCases []ast.Stmt
	for _, statement := range dispatch.Body.List {
		clause := statement.(*ast.CaseClause)
		if len(clause.List) != 1 {
			continue
		}
		name, ok := clause.List[0].(*ast.Ident)
		if !ok {
			continue
		}
		switch name.Name {
		case "thumbShiftImmediate", "thumbMoveImmediate", "thumbCompareImmediate",
			"thumbAddImmediate", "thumbSubtractImmediate", "thumbAddSubtract", "thumbALU", "thumbHighRegister":
		default:
			continue
		}
		var text bytes.Buffer
		if err := format.Node(&text, fset, clause); err != nil {
			return err
		}
		parsed, err := parser.ParseFile(fset, "dead-flags.go", "package interpreter\nfunc deadFlags() { switch in.appOp {"+text.String()+"} }", 0)
		if err != nil {
			return err
		}
		dead := parsed.Decls[0].(*ast.FuncDecl).Body.List[0].(*ast.SwitchStmt).Body.List[0].(*ast.CaseClause)
		dead.List[0] = &ast.BinaryExpr{X: ast.NewIdent(name.Name), Op: token.ADD, Y: ast.NewIdent("thumbDeadFlagsOffset")}
		// omitDeadFlags visits statement lists; wrap the case once so flag
		// setters directly in its body receive the same transformation.
		wrapper := &ast.SwitchStmt{Body: &ast.BlockStmt{List: []ast.Stmt{dead}}}
		omitDeadFlags(wrapper)
		declaration := &ast.DeclStmt{Decl: &ast.GenDecl{Tok: token.CONST, Specs: []ast.Spec{
			&ast.ValueSpec{Names: []*ast.Ident{ast.NewIdent("flagsLive")}, Values: []ast.Expr{ast.NewIdent("false")}},
		}}}
		dead.Body = append([]ast.Stmt{declaration}, dead.Body...)
		deadCases = append(deadCases, dead)
	}
	dispatch.Body.List = append(dispatch.Body.List, deadCases...)
	return nil
}

// Keep architectural instruction bodies in the guarded source. The generated
// application executor may omit a flag write only when translation proved that
// a later, non-faulting instruction overwrites it before any observable exit.
func omitDeadFlags(stmt ast.Stmt) {
	var lists []*[]ast.Stmt
	ast.Inspect(stmt, func(node ast.Node) bool {
		switch item := node.(type) {
		case *ast.BlockStmt:
			lists = append(lists, &item.List)
		case *ast.CaseClause:
			lists = append(lists, &item.Body)
		case *ast.CallExpr:
			if name, ok := item.Fun.(*ast.Ident); ok && name.Name == "addWithCarry" {
				name.Name = "addWithLiveFlags"
				item.Args = append(item.Args, ast.NewIdent("flagsLive"))
			}
		}
		return true
	})
	for _, list := range lists {
		for index, statement := range *list {
			expression, ok := statement.(*ast.ExprStmt)
			if !ok {
				continue
			}
			call, ok := expression.X.(*ast.CallExpr)
			if !ok {
				continue
			}
			method, ok := call.Fun.(*ast.SelectorExpr)
			if !ok {
				continue
			}
			receiver, ok := method.X.(*ast.Ident)
			if !ok || receiver.Name != "b" {
				continue
			}
			switch method.Sel.Name {
			case "setNZ", "setNZC", "setNZCV":
				(*list)[index] = &ast.IfStmt{
					Cond: ast.NewIdent("flagsLive"),
					Body: &ast.BlockStmt{List: []ast.Stmt{statement}},
				}
			}
		}
	}
}
